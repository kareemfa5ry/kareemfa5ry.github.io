// Content -> cv/*.tex. `node scripts/cv/generate.mjs` writes both CVs; `--check` exits 1 when a .tex is stale
// or its sha256 differs from cv/built-from.json (the PDF was not rebuilt). See scripts/README.md.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { bulletsFor } from "../../src/site/bullets.ts";
import * as contact from "../../src/site/contact.ts";
import { CV_FILES } from "../../src/site/cv_files.ts";
import { EDUCATION, LANGUAGES } from "../../src/site/education.ts";
import { monthLabel } from "../../src/site/month.ts";
import { PROFILE_SUMMARY } from "../../src/site/profile.ts";
import {
  educationBlock,
  headerBlock,
  languagesBlock,
  profileBlock,
  projectBlock,
  roleBlock,
  skillsBlock,
} from "./latex.mjs";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const FIRST_LINE = "% generated by npm run cv:generate; edit src/content, not this file";
const lf = (text) => text.replace(/\r\n/g, "\n");
export const sha256 = (text) => createHash("sha256").update(lf(text)).digest("hex");

// Every entry of a collection, parsed from its front matter, sorted by file name.
function loadCollection(name) {
  const dir = join(ROOT, "src/content", name);
  return readdirSync(dir)
    .filter((file) => file.endsWith(".md"))
    .sort()
    .map((file) => {
      const match = readFileSync(join(dir, file), "utf8").match(/^---\r?\n([\s\S]*?)\r?\n---/);
      if (!match) throw new Error(`cv: ${name}/${file}: no front matter`);
      return { id: file.slice(0, -3), data: parse(match[1]) };
    });
}

const inListOrder = (entries, ids, kind, skipMissing) =>
  ids.flatMap((id) => {
    const found = entries.find((entry) => entry.id === id);
    if (found) return [found];
    if (!skipMissing) throw new Error(`cv: unknown ${kind} id "${id}"`);
    console.warn(`cv: skill "${id}" not found in src/content/skills, skipped`);
    return [];
  });

function document(cv, content) {
  const header = headerBlock(
    {
      name: contact.LEGAL_NAME,
      headline: cv.headline,
      location: contact.LOCATION,
      email: contact.EMAIL,
      linkedinLabel: contact.LINKEDIN_LABEL,
      linkedinUrl: contact.LINKEDIN_URL,
    },
    `${cv.id} header`,
  );
  const roles = [...content.experience].sort((a, b) => a.data.order - b.data.order);
  const blocks = [
    header,
    profileBlock(cv.summary || PROFILE_SUMMARY, "profile.ts"),
    skillsBlock(inListOrder(content.skills, cv.skills, "skill", true)),
    "\\section{Experience}",
    ...roles.map((role) => roleBlock(role, bulletsFor(role.data.bullets, cv.id), monthLabel)),
    "\\section{Projects}",
    ...inListOrder(content.projects, cv.projects, "project", false).map((p) =>
      projectBlock(p, bulletsFor(p.data.bullets, cv.id)),
    ),
    educationBlock(EDUCATION),
    languagesBlock(LANGUAGES),
  ];
  const body = blocks.join("\n\n").replace(/^(\\section\{[^}]*\})\n\n/gm, "$1\n");
  return [FIRST_LINE, "\\input{preamble}", "\\begin{document}", "", body, "", "\\end{document}", ""].join("\n");
}

export function generate() {
  const content = Object.fromEntries(["experience", "projects", "skills"].map((n) => [n, loadCollection(n)]));
  return CV_FILES.map((cv) => ({ cv, name: `${basename(cv.href, ".pdf")}.tex`, text: document(cv, content) }));
}

function check(outputs) {
  const builtPath = join(ROOT, "cv/built-from.json");
  const built = JSON.parse(readFileSync(builtPath, "utf8"));
  const problems = [];
  for (const { cv, name, text } of outputs) {
    const disk = lf(readFileSync(join(ROOT, "cv", name), "utf8"));
    if (disk !== text) problems.push(`cv: ${name} stale, run npm run cv:generate`);
    else if (built[name] !== sha256(text)) problems.push(`cv: ${basename(cv.href)} not rebuilt, run npm run cv:pdf`);
  }
  problems.forEach((line) => console.error(line));
  return problems.length ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = generate();
  if (process.argv.includes("--check")) {
    process.exitCode = check(outputs);
  } else {
    outputs.forEach(({ name, text }) => writeFileSync(join(ROOT, "cv", name), text));
    console.log(`cv: wrote ${outputs.map((o) => o.name).join(", ")}`);
  }
}
