// CV LaTeX generator (scripts/cv/): escaping, the Unicode map, and byte-identical output.
import assert from "node:assert/strict";
import { test } from "node:test";
import { generate } from "../../scripts/cv/generate.mjs";
import { escapeTex } from "../../scripts/cv/latex.mjs";

test("every special character is escaped, once", () => {
  assert.equal(escapeTex("\\"), "\\textbackslash{}");
  assert.equal(escapeTex("& % $ # _ { }"), "\\& \\% \\$ \\# \\_ \\{ \\}");
  assert.equal(escapeTex("~"), "\\textasciitilde{}");
  assert.equal(escapeTex("^"), "\\textasciicircum{}");
  assert.equal(escapeTex("a\\&"), "a\\textbackslash{}\\&");
});

test("mapped Unicode becomes LaTeX", () => {
  assert.equal(escapeTex("2014–2016 — a · b × c"), "2014--2016 --- a \\textperiodcentered{} b \\texttimes{} c");
});

test("an unmapped character stops the run and names its source", () => {
  assert.throws(() => escapeTex("caf\u00e9", "air-arabia"), /air-arabia.*U\+e9/);
});

test("two generations are byte-identical and complete", () => {
  const first = generate();
  assert.deepEqual(generate(), first);
  assert.equal(first.length, 2);
  for (const { text } of first) {
    assert.ok(text.startsWith("% generated by npm run cv:generate"));
    assert.ok(text.endsWith("\\end{document}\n"));
    assert.ok(!text.includes("\r"));
  }
});
